-- Run this once in Supabase: SQL Editor > New query > Run.
-- Then create two authorised users in Authentication > Users.
-- Disable public sign-ups after creating both users.

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  menu text not null check (menu in ('Original','Mix','Special','Extra Special')),
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price > 0),
  total numeric(10,2) not null check (total = quantity * unit_price),
  payment_type text not null check (payment_type in ('cash','qr')),
  note text
);

alter table public.sales enable row level security;

drop policy if exists "Authorised POS users can read sales" on public.sales;
create policy "Authorised POS users can read sales"
on public.sales for select to authenticated using (true);

drop policy if exists "Authorised POS users can add sales" on public.sales;
create policy "Authorised POS users can add sales"
on public.sales for insert to authenticated with check (true);

-- No update/delete policy is created: transactions cannot be edited or deleted
-- from this starter app. This protects the sales record from accidental changes.

grant select, insert on public.sales to authenticated;
grant usage, select on sequence public.sales_id_seq to authenticated;